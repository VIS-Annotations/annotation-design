"""Build the web images from the source PNGs. Run from the repo root:  python3 tools/make_images.py

- images/web/<id>-card.webp  gallery cards, at most 960 px wide
- images/web/<id>.webp       detail view, at most 2000 px wide
- considerations/web/<n>.webp|png  the six sketches, cut from Figure 1 of the published paper
The source PNGs stay as they are and remain the fallback.

To recut the sketches, render page 1 of the published PDF at 600 dpi first:
  pdftoppm -f 1 -l 1 -r 600 -png paper.pdf page   ->  page-01.png
  python3 tools/make_images.py page-01.png
"""
import json, re, sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent

def fit(im, max_w):
    if im.width <= max_w:
        return im
    return im.resize((max_w, round(im.height * max_w / im.width)), Image.LANCZOS)

def flatten(im):
    im = im.convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255))
    return Image.alpha_composite(bg, im).convert("RGB")

# gallery: only the figures the dataset uses
src = (ROOT / "data/figures.js").read_text()
paths = re.findall(r'img:\s*"(images/[^"]+)"', src)
out = ROOT / "images/web"
out.mkdir(exist_ok=True)
sizes = {}
for p in paths:
    im = flatten(Image.open(ROOT / p))
    stem = Path(p).stem
    fit(im, 960).save(out / f"{stem}-card.webp", "WEBP", quality=86, method=6)
    fit(im, 2000).save(out / f"{stem}.webp", "WEBP", quality=90, method=6)
    sizes[stem] = [im.width, im.height]

# sketches: the six panels of Figure 1, inside their 1 px frames (page rendered at 600 dpi)
PANELS = {
    "1-audience": (375, 2571, 2454, 3222),
    "2-hierarchy": (2480, 2571, 4559, 3222),
    "3-associate-placement": (375, 3242, 2454, 3909),
    "4-association": (2480, 3242, 4559, 3909),
    "5-cohesion": (375, 3940, 2454, 4562),
    "6-amount": (2480, 3940, 4559, 4562),
}
if len(sys.argv) > 1:
    page = Image.open(sys.argv[1]).convert("RGB")
    cout = ROOT / "considerations/web"
    cout.mkdir(exist_ok=True)
    for name, (x0, y0, x1, y1) in PANELS.items():
        im = fit(page.crop((x0 + 4, y0 + 4, x1 - 3, y1 - 3)), 1600)
        im.save(cout / f"{name}.webp", "WEBP", quality=90, method=6)
        im.save(cout / f"{name}.png", optimize=True)
        print(name, im.size)

(ROOT / "data/sizes.js").write_text(
    "// generated by tools/make_images.py: natural pixel sizes, so cards reserve their space\n"
    "window.FIGURE_SIZES = " + json.dumps(sizes, separators=(",", ":")) + ";\n"
)
print(len(paths), "figures")
